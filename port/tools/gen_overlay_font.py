#!/usr/bin/env python3
"""Writes platform/overlay_font.h: the ASCII glyphs 32..126 of a PSF1 console font as 8x16 bitmaps.

    python3 -I tools/gen_overlay_font.py /usr/share/consolefonts/Lat15-Fixed16.psf.gz > platform/overlay_font.h

Lat15-Fixed16 comes from console-setup and is the public domain misc-fixed 8x16 face.
"""
import gzip
import sys

data = open(sys.argv[1], "rb").read()
if data[:2] == b"\x1f\x8b":
    data = gzip.decompress(data)
assert data[:2] == b"\x36\x04", "not a PSF1 font"
height = data[3]
assert height == 16
glyphs = data[4:]

print("// Generated by tools/gen_overlay_font.py from the console font Lat15-Fixed16 (public domain).")
print("// ASCII 32..126, 16 rows of 8 pixels each; the top bit is the leftmost pixel.")
print("#pragma once")
print("#include <stdint.h>")
print()
print("static const uint8_t kOverlayFont[95][16] = {")
for c in range(32, 127):
    row = ", ".join("0x%02X" % b for b in glyphs[c * height:(c + 1) * height])
    print("    {%s}, // %s" % (row, repr(chr(c)) if chr(c) not in "\\" else "backslash"))
print("};")
